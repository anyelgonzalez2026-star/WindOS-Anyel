export const APP_MAP = new Map(APPS.map((a) => [a.id, a]));

export function getApp(id: string): AppDefinition | undefined {
  return APP_MAP.get(id);
}

export const CORE_APPS = APPS.filter((a) => a.systemCritical).map((a) => a.id);

const screenshotPairs: [string, string, string][] = [
  ["Dashboard", "#eef2fb", "#dfe7f7"],
  ["Workspace", "#f7f4ee", "#e9e1d5"],
  ["Detail view", "#edf7f2", "#d9ece2"],
];

export const STORE_CATALOG: StorePackage[] = APPS.map((appDef) => ({
  app: appDef,
  screenshots: screenshotPairs.map(([title, from, to]) => ({ title, from, to })),
  whatsNew: [
    "Refined window chrome and faster first paint",
    "Full integration with WindOS permissions and search",
    "Bug fixes for touch input and keyboard navigation",
  ],
  installs: `${(appDef.ratingCount / 10).toFixed(1)}k`,
}));

export const featuredApps = APPS.filter((a) => a.featured).sort(
  (a, b) => (a.featuredRank ?? 99) - (b.featuredRank ?? 99),
);

export const APP_CATEGORIES = Array.from(new Set(APPS.map((a) => a.category))).sort();

export function appsByCategory(category: string): AppDefinition[] {
  return APPS.filter((a) => a.category === category);
}

/** App ids preinstalled on a fresh WindOS install. */
export const PREINSTALLED = APPS.filter((a) => a.builtin).map((a) => a.id);
