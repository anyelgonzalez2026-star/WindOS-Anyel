const base = {
  publisher: "WindOS Foundation",
  version: "1.0.0",
  rating: 4.8,
  ratingCount: 1200,
};

function app(
  id: string,
  name: string,
  tagline: string,
  description: string,
  icon: LucideIcon,
  color: string,
  category: string,
  defaultSize: { w: number; h: number },
  extra: Partial<AppDefinition> = {},
): AppDefinition {
  return {
    ...base,
    id,
    name,
    tagline,
    description,
    icon,
    color,
    category,
    sizeMb: 12,
    permissions: ["files"],
    builtin: true,
    defaultSize,
    ...extra,
  };
}

